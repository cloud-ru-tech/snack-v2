import { SUN_SIZE } from '../constants';
import { SunSize } from '../types';

/**
 * Толщина луча по размерам, в единицах `viewBox` (кадр 24 у всех размеров).
 *
 * Пути солнца нарисованы в кадре 24, а сам `<svg>` масштабируется CSS'ом до размера
 * иконки — значит видимая толщина равна `strokeWidth × размер / 24`. Поэтому число
 * здесь пересчитано от эталона Figma, а не взято из макета напрямую:
 *
 * | размер | иконка | эталон Figma | `strokeWidth` |
 * |--------|--------|--------------|---------------|
 * | `xs`   | 16     | 1            | 1.5           |
 * | `s`    | 24     | 1.5          | 1.5           |
 * | `m`    | 32     | 2            | 1.5           |
 * | `l`    | 40     | 2.5          | 1.5           |
 *
 * Эталон — токен `density.icon.strokeWeight.<size>` в desktop compact; в других режимах
 * размер иконки и токен растут пропорционально.
 */
export const SUN_STROKE_WIDTH: Record<SunSize, number> = {
  [SUN_SIZE.XS]: 1.5,
  [SUN_SIZE.S]: 1.5,
  [SUN_SIZE.M]: 1.5,
  [SUN_SIZE.L]: 1.5,
};
