/**
 * Зарезервированные токены спецсимволов: движок подставляет их в `{{token}}` сам, передавать через `t`
 * не нужно. Типобезопасный `t` исключает эти имена из обязательных плейсхолдеров. Имена зарезервированы —
 * обычная переменная интерполяции с таким именем будет перекрыта спецсимволом.
 *
 * Значения — явные \u-escape: невидимые символы видны в diff и не теряются при копировании.
 */
export const SPECIAL_CHARS = {
  nbsp: '\u00A0', // неразрывный пробел
  nnbsp: '\u202F', // узкий неразрывный пробел (перед единицами: «100{{nnbsp}}₽»)
  thinsp: '\u2009', // тонкий пробел (разряды: «10{{thinsp}}000»)
  shy: '\u00AD', // мягкий перенос
  ndash: '\u2013', // среднее тире
  mdash: '\u2014', // длинное тире
  hellip: '\u2026', // многоточие
  newline: '\n', // перенос строки; для отображения контейнеру нужен white-space: pre-line
} as const;

export type SpecialCharName = keyof typeof SPECIAL_CHARS;
