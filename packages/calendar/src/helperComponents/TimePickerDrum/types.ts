import { WithSupportProps } from '@ds/utils';

import { Size } from '../../types';

/**
 * Ограничения допустимых значений в колонках барабана времени.
 * Приоритет: непустой whitelist `allowed*` для соответствующей колонки; иначе — нижняя граница `min*`; иначе — полный диапазон.
 */
export type TimePickerDrumCustomOptions = {
  /** Whitelist часов (0–23): в колонке часов доступны только перечисленные значения. */
  allowedHours?: number[];
  /** Whitelist минут (0–59): в колонке минут доступны только перечисленные значения. */
  allowedMinutes?: number[];
  /** Whitelist секунд (0–59): в колонке секунд доступны только перечисленные значения. */
  allowedSeconds?: number[];
  /** Нижняя граница часов: доступны значения от этого часа до 23 включительно. */
  minHour?: number;
  /** Нижняя граница минут: доступны значения от этой минуты до 59 включительно. */
  minMinute?: number;
  /** Нижняя граница секунд: доступны значения от этой секунды до 59 включительно. */
  minSecond?: number;
};

export type TimePickerDrumProps = WithSupportProps<{
  /** Размер по оси Figma `size` календаря (высота строк барабана и отступы). */
  size?: Size;
  /** Показывать третью колонку секунд (`secondsList` в макете). Если `false`, колонка скрыта и `onSecondsChange` не используется. */
  showSeconds?: boolean;
  /** Текст даты над дисплеем времени (локализуется снаружи). В подписи выводится только дата; время — в `timeRow`. Допускается ISO или строка, распознаваемая `Date.parse`. */
  selectedDateLabel?: string;
  /** Текущий выбранный час (0–23), контролируемое значение колонки часов. */
  hours: number;
  /** Текущая выбранная минута (0–59), контролируемое значение колонки минут. */
  minutes: number;
  /** Текущая выбранная секунда (0–59), контролируемое значение колонки секунд. Учитывается при `showSeconds === true`. */
  seconds?: number;
  /**
   * Вызывается при смене часа после жеста (отпускание указателя / `lostpointercapture`) или после паузы при прокрутке колесом,
   * а также при автоподгонке под `customOptions`. В контролируемом режиме обработчик обязан записать переданный `value` в состояние,
   * иначе эффект подгонки может вызываться на каждом рендере.
   */
  onHoursChange(value: number): void;
  /**
   * Вызывается при смене минуты после жеста или после паузы при прокрутке колесом, а также при автоподгонке под `customOptions`.
   * В контролируемом режиме обработчик обязан записать переданный `value` в состояние, иначе эффект подгонки может вызываться на каждом рендере.
   */
  onMinutesChange(value: number): void;
  /**
   * Вызывается при смене секунды после жеста или после паузы при прокрутке колесом, а также при автоподгонке под `customOptions`.
   * Нужен при `showSeconds === true`. В контролируемом режиме обработчик обязан записать переданный `value` в состояние,
   * иначе эффект подгонки может вызываться на каждом рендере.
   */
  onSecondsChange?(value: number): void;
  /**
   * Ограничение допустимых значений в колонках: whitelist (`allowed*`) или нижняя граница (`min*`).
   * Если задан непустой `allowed*` после нормализации, для этой колонки используется только он; иначе при наличии `min*` — диапазон от `min` до максимума (часы 0–23, минуты и секунды 0–59).
   * При несовпадении текущего `hours` / `minutes` / `seconds` с допустимым набором компонент подставит ближайшее допустимое значение через соответствующий `on*Change`.
   */
  customOptions?: TimePickerDrumCustomOptions;
  /** Дополнительный CSS-класс корневого контейнера барабана. */
  className?: string;
}>;
